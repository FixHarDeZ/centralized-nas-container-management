#!/usr/bin/env python3
"""Generate n8n/workflows/Presenter_Shots.json from core.js (single source of the rules).

    python3 n8n/presenter-shots/build_workflow.py          # write the workflow JSON
    python3 n8n/presenter-shots/build_workflow.py --check  # exit 1 if the committed JSON is stale

Edit core.js (and its tests), never the Code nodes in n8n: the drift test
(tests/test_presenter_shots_workflow.py) fails when the two disagree.
"""
import json
import os
import sys
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "workflows", "Presenter_Shots.json")
NS = uuid.UUID("6f1c5c1e-8a51-4c43-9d4a-2b8a0b6e7a11")

TELEGRAM_CREDENTIAL = {"telegramApi": {"id": "QiUZ8rINLwwPL1qu", "name": "Secretary Bot"}}
FIX_CHAT_ID = "8663614341"
ERROR_WORKFLOW = "SzcBUowHn6PKGUlF"  # Secretary Error Alerter
TICK_MIN = 5

HEADER = "// AUTO-GENERATED by n8n/presenter-shots/build_workflow.py from core.js — edit core.js, then rebuild.\n"


def embed(core_src):
    return "const core = (() => { const module = { exports: {} };\n" + core_src + "\nreturn module.exports; })();\n"


def event_code(core_src):
    return HEADER + embed(core_src) + r"""
const crypto = require('crypto');
const item = $input.first().json;
const headers = item.headers || {};
const want = String($env.CLIP_INTAKE_TOKEN || '');
const got = String(headers['x-clip-token'] || '');
const a = Buffer.from(got), b = Buffer.from(want);
if (!want || a.length !== b.length || !crypto.timingSafeEqual(a, b)) {
  return [{ json: { code: 401, body: { ok: false, error: 'bad token' } } }];
}
const sd = $getWorkflowStaticData('global');
const r = core.apply(sd.state || core.emptyState(), item.body || {}, Date.now());
if (r.code === 200) sd.state = r.state;   // rejected events never touch the stored state
return [{ json: { code: r.code, body: r.body } }];
"""


def tick_code(core_src):
    return HEADER + embed(core_src) + f"""
// READ-ONLY on purpose: writing static data here could clobber a concurrent webhook execution.
// stalls() fires each alert once per tick window (plus an hourly repeat), so no dedup state is needed.
const sd = $getWorkflowStaticData('global');
const hits = core.stalls(sd.state || core.emptyState(), Date.now(), {TICK_MIN} * 60 * 1000);
return hits.map((h) => ({{ json: h }}));
"""


def node_id(name):
    return str(uuid.uuid5(NS, name))


def build():
    with open(os.path.join(HERE, "core.js"), encoding="utf-8") as fh:
        core_src = fh.read()
    nodes = [
        {"id": node_id("Shot Event"), "name": "Shot Event", "type": "n8n-nodes-base.webhook", "typeVersion": 2,
         "position": [0, 0], "webhookId": node_id("webhook:presenter-shots"),
         "parameters": {"httpMethod": "POST", "path": "presenter-shots", "responseMode": "responseNode", "options": {}}},
        {"id": node_id("Apply event"), "name": "Apply event", "type": "n8n-nodes-base.code", "typeVersion": 2,
         "position": [240, 0], "parameters": {"mode": "runOnceForAllItems", "jsCode": event_code(core_src)}},
        {"id": node_id("Respond"), "name": "Respond", "type": "n8n-nodes-base.respondToWebhook", "typeVersion": 1.1,
         "position": [480, 0],
         "parameters": {"respondWith": "json", "responseBody": "={{ JSON.stringify($json.body) }}",
                        "options": {"responseCode": "={{ $json.code }}"}}},
        {"id": node_id("Every 5 min"), "name": "Every 5 min", "type": "n8n-nodes-base.scheduleTrigger",
         "typeVersion": 1.2, "position": [0, 240],
         "parameters": {"rule": {"interval": [{"field": "minutes", "minutesInterval": TICK_MIN}]}}},
        {"id": node_id("Find stalls"), "name": "Find stalls", "type": "n8n-nodes-base.code", "typeVersion": 2,
         "position": [240, 240], "parameters": {"mode": "runOnceForAllItems", "jsCode": tick_code(core_src)}},
        {"id": node_id("Alert Fix"), "name": "Alert Fix", "type": "n8n-nodes-base.telegram", "typeVersion": 1.2,
         "position": [480, 240], "credentials": TELEGRAM_CREDENTIAL,
         "parameters": {"chatId": FIX_CHAT_ID,
                        "text": "={{ $json.text }}\n\nงาน: {{ $json.job }} — ทักไอยูว่า \"ทำ presenter {{ $json.job }} ต่อ\" ถ้าไอยูหลุดไป",
                        "additionalFields": {"appendAttribution": False}}},
    ]
    connections = {
        "Shot Event": {"main": [[{"node": "Apply event", "type": "main", "index": 0}]]},
        "Apply event": {"main": [[{"node": "Respond", "type": "main", "index": 0}]]},
        "Every 5 min": {"main": [[{"node": "Find stalls", "type": "main", "index": 0}]]},
        "Find stalls": {"main": [[{"node": "Alert Fix", "type": "main", "index": 0}]]},
    }
    settings = {"executionOrder": "v1", "timezone": "Asia/Bangkok", "errorWorkflow": ERROR_WORKFLOW,
                "saveDataSuccessExecution": "none", "saveDataErrorExecution": "all", "executionTimeout": 60}
    return {"name": "Presenter Shots", "nodes": nodes, "connections": connections, "settings": settings}


def render():
    return json.dumps(build(), ensure_ascii=False, indent=2) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        cur = ""
        if os.path.exists(OUT):
            with open(OUT, encoding="utf-8") as fh:
                cur = fh.read()
        if cur != text:
            sys.exit("Presenter_Shots.json is stale: run python3 n8n/presenter-shots/build_workflow.py")
        print("Presenter_Shots.json up to date")
        return
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
